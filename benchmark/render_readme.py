"""Render the README benchmark section from summary.json.

    python benchmark/render_readme.py

The README block between the BENCHMARK markers is generated,
so the published numbers can never drift from summary.json (tests enforce this).
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- BENCHMARK:START (generated by benchmark/render_readme.py) -->", "<!-- BENCHMARK:END -->"


def totals(data):
    cases = sum(c["total"] for s in data["sets"] for c in s["classes"])
    ok = sum(c["correct"] for s in data["sets"] for c in s["classes"])
    return cases, ok


def render_block(data):
    cases, ok = totals(data)
    fa = sum(s["false_accepts"] for s in data["sets"])
    fr = sum(s["false_rejects"] for s in data["sets"])
    L = [
        START, "## Benchmark", "",
        f"CiteGuard was run against {cases} labeled references ({data['unique_references']} distinct references) "
        "built from real Crossref records, mixing correct citations with fabricated DOIs, mismatched titles, "
        f"retracted papers and invented references. **{ok}/{cases} = {100 * ok / cases:.1f}%** received the expected verdict, "
        f"with {fa} wrong acceptances and {fr} wrong rejections. "
        f"Measured {data['measured_on']} on code version `{data['code_version']}`.", "",
        "```mermaid", "xychart-beta", '    title "Share of cases with the expected verdict (%)"',
        "    x-axis [" + ", ".join(f'"{x["short_en"] if "short_en" in x else x["id"]}"' for x in data["sets"]) + "]",
        '    y-axis "Percent" 80 --> 100',
        "    bar [" + ", ".join(f"{100 * sum(c['correct'] for c in x['classes']) / sum(c['total'] for c in x['classes']):.1f}" for x in data["sets"]) + "]",
        "```", "",
        "| Set | Cases | Expected verdict | Wrong acceptances | Wrong rejections |",
        "|---|---:|---:|---:|---:|",
    ]
    for s in data["sets"]:
        sc = sum(c["correct"] for c in s["classes"])
        st = sum(c["total"] for c in s["classes"])
        L.append(f"| {s['label_en']} | {st} | {sc} ({100 * sc / st:.1f}%) | {s['false_accepts']} | {s['false_rejects']} |")
    L += [f"| **Total** | **{cases}** | **{ok} ({100 * ok / cases:.1f}%)** | **{fa}** | **{fr}** |", "",
          "A miss means a genuine citation that the tool declined to confirm; it is never a bad citation accepted.", "",
          "<details>", "<summary>Results by case type</summary>", ""]
    for s in data["sets"]:
        L += [f"**{s['label_en']}**", "", "| Case | Expected verdict | Correct |", "|---|---|---|"]
        for c in s["classes"]:
            L.append(f"| {c['label_en']} | `{c['expected']}` | {c['correct']}/{c['total']} |")
        L.append("")
    L += ["</details>", "", "**Limitations**", ""] + [f"- {x}" for x in data["caveats_en"]] + [
        "", "To reproduce (network access required; set `OPENALEX_API_KEY`, see [Configuration](#configuration)):", "", "```bash",
        "python benchmark/run_benchmark.py --json /tmp/res_original.json",
        "python benchmark/run_benchmark.py --cases benchmark/cases_seed101.jsonl --json /tmp/res_fresh.json",
        "python benchmark/run_benchmark.py --cases benchmark/cases_hard.jsonl --json /tmp/res_hard.json",
        "python benchmark/make_summary.py original=/tmp/res_original.json fresh=/tmp/res_fresh.json hard=/tmp/res_hard.json",
        "python benchmark/render_readme.py    # regenerate this section",
        "```", "",
        "The full write-up, including the bugs the benchmark uncovered, is in [`benchmark/RESULTS.md`](benchmark/RESULTS.md). "
        "The web UI shows the same numbers, served from `benchmark/summary.json` at `/api/benchmark`.",
        END, ""]
    return "\n".join(L)


def main():
    data = json.loads((ROOT / "benchmark" / "summary.json").read_text(encoding="utf-8"))
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    block = render_block(data)
    if START in readme:
        head, rest = readme.split(START, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        readme = head + block + "\n" + tail
    else:                                   # first run: replace the hand-written section
        head, rest = readme.split("## Benchmark", 1)
        tail = "## Verdict System" + rest.split("## Verdict System", 1)[1]
        readme = head + block + "\n" + tail
    (ROOT / "README.md").write_text(readme, encoding="utf-8")
    print("README.md updated")


if __name__ == "__main__":
    main()
