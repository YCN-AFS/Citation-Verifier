"""Render the README benchmark section and docs/benchmark.svg from summary.json.

    python benchmark/render_readme.py

The README block between the BENCHMARK markers and the SVG card are generated,
so the published numbers can never drift from summary.json (tests enforce this).
"""

import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- BENCHMARK:START (generated by benchmark/render_readme.py) -->", "<!-- BENCHMARK:END -->"
BAR = 20


def totals(data):
    cases = sum(c["total"] for s in data["sets"] for c in s["classes"])
    ok = sum(c["correct"] for s in data["sets"] for c in s["classes"])
    return cases, ok


def bar(ok, total):
    filled = round(BAR * ok / total) if total else 0
    return "█" * filled + "░" * (BAR - filled)


def render_svg(data):
    cases, ok = totals(data)
    fa = sum(s["false_accepts"] for s in data["sets"])
    fr = sum(s["false_rejects"] for s in data["sets"])
    W = 760
    rows = []
    y = 238
    for s in data["sets"]:
        sc = sum(c["correct"] for c in s["classes"])
        st = sum(c["total"] for c in s["classes"])
        pct = 100 * sc / st
        rows.append(f'<text x="40" y="{y}" class="lbl">{escape(s["label_en"])}</text>'
                    f'<text x="{W - 40}" y="{y}" class="num" text-anchor="end">{sc}/{st} · {pct:.1f}%</text>')
        rows.append(f'<rect x="40" y="{y + 10}" width="{W - 80}" height="10" rx="5" fill="#1f2a44"/>'
                    f'<rect x="40" y="{y + 10}" width="{(W - 80) * sc / st:.1f}" height="10" rx="5" fill="url(#g)"/>')
        y += 52
    H = y + 14
    stat = lambda x, num, label, col: (
        f'<rect x="{x}" y="84" width="212" height="96" rx="14" fill="#141d36" stroke="#26335a"/>'
        f'<text x="{x + 106}" y="136" text-anchor="middle" class="big" fill="{col}">{num}</text>'
        f'<text x="{x + 106}" y="162" text-anchor="middle" class="cap">{label}</text>')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="CiteGuard benchmark: {ok} of {cases} correct, {fa} wrong acceptances">
<defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" stop-color="#34d399"/><stop offset="1" stop-color="#22d3ee"/></linearGradient>
<style>text{{font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif}}.big{{font-size:38px;font-weight:800}}.cap{{font-size:12px;fill:#8ea0c9;letter-spacing:.08em;text-transform:uppercase}}.lbl{{font-size:14px;fill:#dbe4ff;font-weight:600}}.num{{font-size:14px;fill:#9fb0d8;font-family:ui-monospace,Menlo,Consolas,monospace}}</style></defs>
<rect width="{W}" height="{H}" rx="20" fill="#0b1226"/>
<rect x="1" y="1" width="{W - 2}" height="{H - 2}" rx="19" fill="none" stroke="#26335a"/>
<text x="40" y="46" font-size="22" font-weight="800" fill="#f1f5ff">CiteGuard · Verified accuracy</text>
<text x="40" y="66" font-size="12" fill="#8ea0c9">{cases} evaluations · {data["unique_references"]} distinct references · measured {data["measured_on"]} · code {data["code_version"]}</text>
{stat(40, fa, "Wrong acceptances", "#34d399")}{stat(274, fr, "Wrong rejections", "#34d399")}{stat(508, f"{100 * ok / cases:.1f}%", f"Exact · {ok}/{cases}", "#22d3ee")}
<text x="40" y="214" font-size="12" fill="#8ea0c9" letter-spacing="1.2">BY BENCHMARK SET</text>
{"".join(rows)}
</svg>
'''


def render_block(data):
    cases, ok = totals(data)
    fa = sum(s["false_accepts"] for s in data["sets"])
    fr = sum(s["false_rejects"] for s in data["sets"])
    L = [
        START, "## Benchmark", "",
        '<p align="center"><img src="docs/benchmark.svg" alt="Benchmark summary" width="760"></p>', "",
        f"![wrong acceptances](https://img.shields.io/badge/wrong%20acceptances-{fa}-brightgreen) "
        f"![wrong rejections](https://img.shields.io/badge/wrong%20rejections-{fr}-brightgreen) "
        f"![accuracy](https://img.shields.io/badge/exact%20match-{ok}%2F{cases}-blue) "
        f"![refs](https://img.shields.io/badge/distinct%20references-{data['unique_references']}-lightgrey)", "",
        f"Measured on labeled references built from real Crossref records (`benchmark/`) — "
        f"{data['measured_on']}, code version `{data['code_version']}`. "
        f"**{ok}/{cases} = {100 * ok / cases:.1f}%** matched the expected verdict "
        f"({data['unique_references']} distinct references). "
        "A miss is a genuine citation the tool declined to confirm, never a wrong acceptance.", "",
    ]
    for s in data["sets"]:
        sc = sum(c["correct"] for c in s["classes"])
        st = sum(c["total"] for c in s["classes"])
        L += [f"<details open><summary><b>{s['label_en']}</b> — {sc}/{st} ({100 * sc / st:.1f}%)</summary>", "",
              "| Case | Expected verdict | Correct | |", "|---|---|---|---|"]
        for c in s["classes"]:
            mark = "✅" if c["correct"] == c["total"] else "⚠️"
            L.append(f"| {c['label_en']} | `{c['expected']}` | {c['correct']}/{c['total']} | `{bar(c['correct'], c['total'])}` {mark} |")
        L += ["", "</details>", ""]
    L += ["**Caveats**", ""] + [f"- {x}" for x in data["caveats_en"]] + [
        "", "Reproduce (needs network; `OPENALEX_API_KEY` recommended, see `.env.example`):", "", "```bash",
        "python benchmark/run_benchmark.py --json /tmp/res_original.json",
        "python benchmark/run_benchmark.py --cases benchmark/cases_seed101.jsonl --json /tmp/res_fresh.json",
        "python benchmark/run_benchmark.py --cases benchmark/cases_hard.jsonl --json /tmp/res_hard.json",
        "python benchmark/make_summary.py original=/tmp/res_original.json fresh=/tmp/res_fresh.json hard=/tmp/res_hard.json",
        "python benchmark/render_readme.py          # refresh README block + docs/benchmark.svg",
        "```", "",
        "Full write-up, including the bugs the benchmark found: [`benchmark/RESULTS.md`](benchmark/RESULTS.md). "
        "The same numbers are shown in the web UI (served from `benchmark/summary.json` at `/api/benchmark`).",
        END, ""]
    return "\n".join(L)


def main():
    data = json.loads((ROOT / "benchmark" / "summary.json").read_text(encoding="utf-8"))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "benchmark.svg").write_text(render_svg(data), encoding="utf-8")
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    block = render_block(data)
    if START in readme:
        head, rest = readme.split(START, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        readme = head + block + "\n" + tail
    else:                                   # first run: replace the hand-written section
        head, rest = readme.split("## Benchmark", 1)
        tail = "## Verdict System" + rest.split("## Verdict System", 1)[1]
        readme = head + block + "\n" + tail
    (ROOT / "README.md").write_text(readme, encoding="utf-8")
    print("README.md and docs/benchmark.svg updated")


if __name__ == "__main__":
    main()
